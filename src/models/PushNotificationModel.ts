import mongoose from "mongoose";

const PushNotificationModel = new mongoose.Schema({
  user: {
    type: mongoose.Schema.Types.ObjectId,
    ref: "User",
    required: true,
  },
  title: {
    type: String,
    required: true,
  },
  content: {
    type: String,
    required: true,
  },
  launch_url: {
    type: String,
    required: false,
  },
  viewed: {
    type: Boolean,
    required: true,
    default: false,
  },
  createdAt: {
    type: Date,
    required: true,
    default: Date.now,
  },
});

export default mongoose.models?.PushNotification ||
  mongoose.model("PushNotification", PushNotificationModel);
