import mongoose from "mongoose";

const RecipeModel = new mongoose.Schema({
  created_by: {
    type: String,
    required: true,
  },
  image: {
    type: String,
    required: true,
  },
  title: {
    type: String,
    required: true,
  },
  ingredients: {
    type: [String],
    required: true,
  },
  steps: {
    type: [String],
    required: true,
  },
});

export default mongoose.models?.Recipe || mongoose.model("Recipe", RecipeModel);
