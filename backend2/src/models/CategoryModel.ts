import mongoose from "mongoose";

const CategoryModel = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  description: {
    type: String,
  },
  image: {
    type: String,
  },
});

export default mongoose.models?.Category ||
  mongoose.model("Category", CategoryModel);
